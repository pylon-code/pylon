import * as NodeCrypto from "node:crypto";
import { stableStringify } from "@t3tools/shared/relaySigning";
import * as Exit from "effect/Exit";
import * as Schema from "effect/Schema";

const Uuid = Schema.String.check(
  Schema.isPattern(/^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i),
);
const Digest = Schema.String.check(Schema.isPattern(/^[0-9a-f]{64}$/));
const NonNegativeInt = Schema.Int.check(Schema.isGreaterThanOrEqualTo(0));
export const ClaudeHistoryMessage = Schema.Struct({
  type: Schema.Literals(["user", "assistant", "system"]),
  uuid: Uuid,
  session_id: Uuid,
  message: Schema.Json,
  parent_tool_use_id: Schema.NullOr(Schema.String),
  parent_agent_id: Schema.NullOr(Schema.String),
});
const decodeMessages = Schema.decodeUnknownExit(Schema.Array(ClaudeHistoryMessage));

/** Only transport IDs regenerated by forkSession are omitted; semantic/tool lineage stays exact. */
export function proveClaudeHistory(raw: unknown, sessionId: string) {
  const decoded = decodeMessages(raw);
  if (Exit.isFailure(decoded)) return undefined;
  const messages = decoded.value;
  if (
    messages.some((message) => message.session_id !== sessionId) ||
    new Set(messages.map((message) => message.uuid)).size !== messages.length
  )
    return undefined;
  const semantic = messages.map(({ uuid: _uuid, session_id: _sessionId, ...message }) => message);
  return {
    messages,
    digest: NodeCrypto.createHash("sha256").update(stableStringify(semantic)).digest("hex"),
  };
}

